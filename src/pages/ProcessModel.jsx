import { useEffect, useState } from 'react'
import { Link, useSearchParams } from 'react-router-dom'
import { ArrowLeft, Check, Download, Info, Loader2, X } from 'lucide-react'
import { api } from '../lib/api'
import ProcessFlow from '../components/process/ProcessFlow'
import Button from '../components/ui/Button'
import EmptyState from '../components/ui/EmptyState'

export default function ProcessModel() {
  const [searchParams] = useSearchParams()
  const processId = searchParams.get('id') || localStorage.getItem('processiq_active_process_id')

  const [processData, setProcessData] = useState(null)
  const [selectedNode, setSelectedNode] = useState(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  useEffect(() => {
    async function fetchModel() {
      setLoading(true)
      setError('')
      try {
        if (processId) {
          const data = await api.processes.get(processId)
          setProcessData(data)
        } else {
          const list = await api.processes.list()
          if (list && list.length > 0) {
            const latest = await api.processes.get(list[0].id)
            setProcessData(latest)
          }
        }
      } catch (err) {
        setError(err.message || 'Failed to load process model.')
      } finally {
        setLoading(false)
      }
    }
    fetchModel()
  }, [processId])

  if (loading) {
    return (
      <div className="flex h-72 items-center justify-center">
        <div className="flex flex-col items-center gap-3">
          <Loader2 size={24} className="animate-spin text-accent" />
          <p className="text-xs text-muted">Loading process flow model...</p>
        </div>
      </div>
    )
  }

  if (error || !processData || !processData.model) {
    return (
      <EmptyState
        title="No Process Model Available"
        description={error || "Analyze a process first to view its dynamic interactive workflow graph."}
        actionLabel="Analyze Process"
        onAction={() => window.location.assign('/analyze')}
      />
    )
  }

  const model = processData.model
  const stats = model.statistics || {
    total_nodes: model.nodes?.length || 0,
    edges: model.edges?.length || 0,
  }

  return (
    <div className="mx-auto max-w-6xl space-y-4">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h2 className="text-xl font-semibold tracking-tight text-fg">{processData.name} - Process Model</h2>
          <p className="mt-1 text-xs text-muted">
            Interactive visualization generated by the Modeler Agent · {stats.total_nodes} nodes · {stats.edges} transitions.
            Click any node to inspect metadata.
          </p>
        </div>
        <Button as={Link} to={`/analysis?id=${processData.id}`} variant="secondary" size="sm">
          <ArrowLeft size={14} />
          Back to analysis
        </Button>
      </div>

      <div className="relative">
        <ProcessFlow
          model={model}
          onNodeClick={(_event, node) => setSelectedNode(node)}
        />

        {/* Node Inspector Panel */}
        {selectedNode && (
          <div className="absolute top-4 right-4 z-20 w-80 rounded-xl border border-line bg-surface/95 p-4 shadow-xl backdrop-blur">
            <div className="flex items-center justify-between border-b border-line pb-2.5">
              <div className="flex items-center gap-2">
                <Info size={15} className="text-accent" />
                <h4 className="text-xs font-semibold text-fg">Node Inspector</h4>
              </div>
              <button
                type="button"
                onClick={() => setSelectedNode(null)}
                className="rounded p-1 text-muted hover:bg-elevated hover:text-fg"
              >
                <X size={14} />
              </button>
            </div>

            <div className="mt-3 space-y-2.5 text-xs">
              <div>
                <p className="text-[10px] uppercase tracking-wide text-faint">Node ID</p>
                <p className="font-mono text-fg font-medium">{selectedNode.id}</p>
              </div>

              <div>
                <p className="text-[10px] uppercase tracking-wide text-faint">Type</p>
                <p className="capitalize text-fg font-medium">
                  {selectedNode.type} {selectedNode.data?.kind ? `(${selectedNode.data.kind})` : ''}
                </p>
              </div>

              <div>
                <p className="text-[10px] uppercase tracking-wide text-faint">Label</p>
                <p className="text-fg font-medium">{selectedNode.data?.label}</p>
              </div>

              {selectedNode.data?.actor && (
                <div>
                  <p className="text-[10px] uppercase tracking-wide text-faint">Responsible Actor</p>
                  <span className="inline-block rounded bg-accent/10 border border-accent/20 px-2 py-0.5 text-accent font-medium mt-0.5">
                    {selectedNode.data.actor}
                  </span>
                </div>
              )}

              {selectedNode.data?.description && (
                <div>
                  <p className="text-[10px] uppercase tracking-wide text-faint">Description</p>
                  <p className="text-muted leading-relaxed mt-0.5">{selectedNode.data.description}</p>
                </div>
              )}
            </div>
          </div>
        )}
      </div>

      <div className="flex flex-wrap items-center justify-between gap-4 text-xs text-muted border-t border-line pt-2">
        <div className="flex flex-wrap gap-4">
          <span className="inline-flex items-center gap-2">
            <span className="h-2.5 w-2.5 rounded-full border border-accent/50 bg-accent/20" /> Start / End Events
          </span>
          <span className="inline-flex items-center gap-2">
            <span className="h-2.5 w-4 rounded-sm border border-line bg-elevated" /> Activity / Task
          </span>
          <span className="inline-flex items-center gap-2">
            <span className="h-2.5 w-2.5 rotate-45 border border-warn/40 bg-warn/20" /> Decision Gateway
          </span>
        </div>
        <p className="text-[11px] text-faint">Drag nodes to rearrange · Zoom with mouse wheel or pinch</p>
      </div>
    </div>
  )
}
